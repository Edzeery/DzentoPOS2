using System.ComponentModel;
using System.Drawing.Drawing2D;
using EZControls.Core.Animation;
using EZControls.Core.Base;
using EZControls.Core.Constants;
using EZControls.Core.Drawing;
using EZControls.Core.Themes;

namespace EZControls.Controls.Toggles;

// ??????????????????????????????????????????????????????????????????????????????
//  EZToggleButton
//
//  A pill-shaped toggle switch with an animated thumb that slides between
//  On and Off positions using time-based interpolation (AnimationState).
//
//  Design:
//    ???????????????????????       ???????????????????????
//    ? ?                   ?  OFF  ?                   ? ?  ON
//    ???????????????????????       ???????????????????????
//
//  The thumb x-position is driven by AnimationState, which interpolates
//  between thumbOffX and thumbOnX over 150 ms using EaseInOut easing.
//
//  Rendering:
//    1. Fill pill background (track).
//    2. Draw thumb circle.
//    3. Optionally draw On/Off label text.
// ??????????????????????????????????????????????????????????????????????????????

/// <summary>
/// An animated pill-shaped toggle switch.
/// Inherits <see cref="EZSelectableBase"/> for checked-state management,
/// <see cref="CheckedChanged"/> event, and accessibility.
/// </summary>
[DefaultEvent(nameof(CheckedChanged))]
[ToolboxBitmap(typeof(CheckBox))]
[DesignerCategory("Code")]
public class EZToggleButton : EZSelectableBase
{
    // ?? Animation ?????????????????????????????????????????????????????????????
    private readonly AnimationState _thumbAnim;
    private System.Windows.Forms.Timer? _animTimer;

    // ?? Colors ????????????????????????????????????????????????????????????????
    private Color _onColor = Color.FromArgb(0, 192, 192);
    private Color _offColor = Color.Red;
    private Color _thumbColor = Color.White;
    private Color _onTextColor = Color.White;
    private Color _offTextColor = Color.White;

    // ?? Layout constants ??????????????????????????????????????????????????????
    private const int InnerGap = 3;   // gap between thumb and track edge

    // ?? Label ?????????????????????????????????????????????????????????????????
    private bool _showLabel = false;
    private string _onText = "ON";
    private string _offText = "OFF";

    // ?? Shadow ????????????????????????????????????????????????????????????????
    private bool _showThumbShadow = true;

    // ??????????????????????????????????????????????????????????????????????????
    //  Constructor
    // ??????????????????????????????????????????????????????????????????????????

    /// <summary>Initialises the toggle with default colors and animation.</summary>
    public EZToggleButton()
    {
        Size = new Size(60, 30);
        Cursor = Cursors.Hand;

        // Start the thumb at the Off position (x = InnerGap).
        _thumbAnim = new AnimationState(InnerGap);

        if (!IsInDesigner)
        {
            _animTimer = new System.Windows.Forms.Timer
            {
                Interval = EZDefaults.AnimationIntervalMs
            };
            _animTimer.Tick += OnAnimationTick;
        }
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Properties
    // ??????????????????????????????????????????????????????????????????????????

    /// <summary>Track color when the toggle is ON.</summary>
    [Category("EZControls")]
    public Color OnColor
    {
        get => _onColor;
        set { _onColor = value; Invalidate(); }
    }

    /// <summary>Track color when the toggle is OFF.</summary>
    [Category("EZControls")]
    public Color OffColor
    {
        get => _offColor;
        set { _offColor = value; Invalidate(); }
    }

    /// <summary>Color of the sliding thumb circle.</summary>
    [Category("EZControls")]
    public Color ThumbColor
    {
        get => _thumbColor;
        set { _thumbColor = value; Invalidate(); }
    }

    /// <summary>
    /// When <see langword="true"/>, renders On/Off label text inside the track.
    /// </summary>
    [Category("EZControls"), DefaultValue(false)]
    public bool ShowLabel
    {
        get => _showLabel;
        set { _showLabel = value; Invalidate(); }
    }

    /// <summary>Label text shown when the toggle is ON.</summary>
    [Category("EZControls"), DefaultValue("ON")]
    public string OnText
    {
        get => _onText;
        set { _onText = value; Invalidate(); }
    }

    /// <summary>Label text shown when the toggle is OFF.</summary>
    [Category("EZControls"), DefaultValue("OFF")]
    public string OffText
    {
        get => _offText;
        set { _offText = value; Invalidate(); }
    }

    /// <summary>When <see langword="true"/>, a subtle drop-shadow is drawn beneath the thumb.</summary>
    [Category("EZControls"), DefaultValue(true)]
    public bool ShowThumbShadow
    {
        get => _showThumbShadow;
        set { _showThumbShadow = value; Invalidate(); }
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Checked ? animate thumb
    // ??????????????????????????????????????????????????????????????????????????

    /// <inheritdoc/>
    protected override void OnCheckedChanged(EventArgs e)
    {
        base.OnCheckedChanged(e);

        // Target: thumb at Off position (left) or On position (right).
        float thumbDiameter = Height - InnerGap * 2;
        float thumbOnX = Width - thumbDiameter - InnerGap;
        float target = Checked ? thumbOnX : InnerGap;

        _thumbAnim.SetTarget(target, 0.15f); // 150 ms transition
        _animTimer?.Start();
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Painting
    // ??????????????????????????????????????????????????????????????????????????

    /// <inheritdoc/>
    protected override void OnPaint(PaintEventArgs e)
    {
        base.OnPaint(e);

        if (Width <= 0 || Height <= 0) return;

        Graphics g = e.Graphics;
        GraphicsHelper.SetHighQuality(g);

        float thumbDiam = Height - InnerGap * 2;
        float thumbOnX = Width - thumbDiam - InnerGap;

        // Blend track color between Off and On based on thumb progress.
        float progress = (Width - InnerGap * 2 - thumbDiam) > 0
            ? (_thumbAnim.Value - InnerGap) / (thumbOnX - InnerGap)
            : 0f;
        progress = Math.Clamp(progress, 0f, 1f);

        Color trackColor = _offColor.Blend(_onColor, progress);

        // ?? Track (pill) ??????????????????????????????????????????????????
        using GraphicsPath trackPath = GraphicsHelper.CreateRoundedPath(
            ClientRectangle, Height / 2f);
        using SolidBrush trackBrush = new(trackColor);
        g.FillPath(trackBrush, trackPath);

        // ?? Label text ????????????????????????????????????????????????????
        if (_showLabel)
            DrawLabel(g, thumbDiam, progress);

        // ?? Thumb shadow ??????????????????????????????????????????????????
        if (_showThumbShadow)
            DrawThumbShadow(g, thumbDiam);

        // ?? Thumb circle ??????????????????????????????????????????????????
        RectangleF thumbRect = new(
            _thumbAnim.Value, InnerGap,
            thumbDiam, thumbDiam);

        using SolidBrush thumbBrush = new(_thumbColor);
        g.FillEllipse(thumbBrush, thumbRect);
    }

    private void DrawLabel(Graphics g, float thumbDiam, float progress)
    {
        // On label: left side (visible when ON)
        Rectangle onRect = new(0, 0, (int)(Width - thumbDiam - InnerGap * 2), Height);
        // Off label: right side (visible when OFF)
        Rectangle offRect = new((int)(thumbDiam + InnerGap * 2), 0, Width, Height);

        using Font labelFont = new(Font.FontFamily, Math.Max(6f, Font.Size - 2f));

        if (progress > 0.5f)
        {
            using SolidBrush b = new(Color.FromArgb((int)(progress * 200), _onTextColor));
            ControlPainter.DrawText(g, onRect, _onText, labelFont, b.Color, ContentAlignment.MiddleCenter);
        }
        else
        {
            using SolidBrush b = new(Color.FromArgb((int)((1 - progress) * 200), _offTextColor));
            ControlPainter.DrawText(g, offRect, _offText, labelFont, b.Color, ContentAlignment.MiddleCenter);
        }
    }

    private void DrawThumbShadow(Graphics g, float thumbDiam)
    {
        RectangleF shadowRect = new(
            _thumbAnim.Value + 1, InnerGap + 2,
            thumbDiam, thumbDiam);

        using SolidBrush shadow = new(Color.FromArgb(30, Color.Black));
        g.FillEllipse(shadow, shadowRect);
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Animation tick
    // ??????????????????????????????????????????????????????????????????????????

    private void OnAnimationTick(object? sender, EventArgs e)
    {
        if (!IsHandleCreated || IsDisposed || !Visible)
        {
            _animTimer?.Stop();
            return;
        }

        if (!_thumbAnim.Tick())
            _animTimer?.Stop();

        Invalidate();
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Lifecycle
    // ??????????????????????????????????????????????????????????????????????????

    /// <inheritdoc/>
    protected override void OnVisibleChanged(EventArgs e)
    {
        base.OnVisibleChanged(e);
        if (!Visible) _animTimer?.Stop();
    }

    /// <inheritdoc/>
    protected override void OnHandleDestroyed(EventArgs e)
    {
        _animTimer?.Stop();
        base.OnHandleDestroyed(e);
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Theming
    // ??????????????????????????????????????????????????????????????????????????

    /// <inheritdoc/>
    public override void ApplyTheme(EZTheme theme)
    {
        Font = theme.DefaultFont;
        _onColor = theme.PrimaryColor;
        _offColor = theme.DisabledColor;
        Invalidate();
    }

    // ??????????????????????????????????????????????????????????????????????????
    //  Dispose
    // ??????????????????????????????????????????????????????????????????????????

    /// <inheritdoc/>
    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _animTimer?.Stop();
            _animTimer?.Dispose();
        }
        base.Dispose(disposing);
    }
}